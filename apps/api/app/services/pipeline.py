SCRIPT_PREAMBLE = '''"""Auto-generated data cleaning script.

Generated by datacleaner. Review before running.
Usage:  python clean.py input.csv cleaned.csv
"""

from __future__ import annotations

import sys

import pandas as pd

_TRUTHY = {"1", "true", "t", "yes", "y"}
_FALSY = {"0", "false", "f", "no", "n", ""}


def _to_bool(value):
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return pd.NA
    text = str(value).strip().lower()
    if text in _TRUTHY:
        return True
    if text in _FALSY:
        return False
    return pd.NA


def clean(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()
'''

SCRIPT_EPILOGUE = '''    return df


def _load(path: str) -> pd.DataFrame:
    if path.lower().endswith(".json"):
        return pd.read_json(path)
    return pd.read_csv(path)


if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else "{read_source}"
    dst = sys.argv[2] if len(sys.argv) > 2 else "{write_target}"
    cleaned = clean(_load(src))
    if dst.lower().endswith(".json"):
        cleaned.to_json(dst, orient="records", indent=2)
    else:
        cleaned.to_csv(dst, index=False)
    print(f"Wrote {{len(cleaned)}} rows to {{dst}}")
'''


def apply_ops(df: pd.DataFrame, ops: list[BaseOp]) -> pd.DataFrame:
    """Apply cleaning ops in order. Raises ValueError on the first failure."""
    result = df
    for index, op in enumerate(ops):
        try:
            result = op.apply(result)
        except Exception as exc:  # noqa: BLE001 - annotate with op context
            raise ValueError(f"Op #{index} ({op.op}) failed: {exc}") from exc
    return result


def generate_script(
    ops: list[BaseOp],
    read_source: str = "input.csv",
    write_target: str = "cleaned.csv",
) -> str:
    body_lines: list[str] = []
    for index, op in enumerate(ops, start=1):
        body_lines.append(f"    # {index}. {op.summary()}")
        for line in op.emit_pandas().splitlines():
            body_lines.append(f"    {line}")
        body_lines.append("")

    body = "\n".join(body_lines)
    epilogue = SCRIPT_EPILOGUE.format(
        read_source=read_source, write_target=write_target
    )
    return SCRIPT_PREAMBLE + body + epilogue


def build_preview(df: pd.DataFrame, limit: int = 50) -> PreviewResponse:
    head = df.head(limit)
    rows: list[dict[str, Any]] = []
    for record in head.to_dict(orient="records"):
        rows.append({k: _safe(v) for k, v in record.items()})
    return PreviewResponse(
        columns=[str(c) for c in df.columns],
        dtypes={str(c): str(df[c].dtype) for c in df.columns},
        rows=rows,
        total_rows=int(df.shape[0]),
    )


def _safe(value: Any) -> Any:
    if value is None:
        return None
    try:
        if pd.isna(value):
            return None
    except (TypeError, ValueError):
        pass
    if isinstance(value, (int, float, bool, str)):
        return value
    return str(value)
